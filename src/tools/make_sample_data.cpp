// Writes the two example files in data/:
//   heatsink_fins_mm.stl           ASCII STL of a small finned heat sink, in millimetres
//   heatsink_nodal_SYNTHETIC.csv   nodal temperatures on the same part, in metres / C
//
// Both are self-created for this project (no third-party geometry). The CSV is
// NOT an ANSYS export - it follows the same column layout but the temperatures
// come from a simple closed-form field (see temperatureAt below).
//
// Usage: wb_make_sample_data <output-dir>

#include "core/io/CsvWriter.h"
#include "core/io/TextFile.h"

#include <cmath>
#include <cstdio>
#include <iostream>
#include <sstream>
#include <string>

namespace {

// Geometry, all in mm. Fins run along y and stand on top of the base plate.
constexpr double kBaseX = 60.0, kBaseY = 40.0, kBaseZ = 5.0;
constexpr int kFins = 6;
constexpr double kFinThickness = 2.0, kFinHeight = 25.0;

double finX0(int i) {
    const double pitch = (kBaseX - kFinThickness) / (kFins - 1);
    return i * pitch;
}

struct Box {
    double x0, y0, z0, x1, y1, z1;
};

void writeQuad(std::ostringstream& out, const double n[3], const double a[3], const double b[3], const double c[3],
               const double d[3]) {
    auto facet = [&](const double* p, const double* q, const double* r) {
        out << "  facet normal " << n[0] << ' ' << n[1] << ' ' << n[2] << "\n    outer loop\n";
        for (const double* v : {p, q, r}) out << "      vertex " << v[0] << ' ' << v[1] << ' ' << v[2] << '\n';
        out << "    endloop\n  endfacet\n";
    };
    facet(a, b, c);
    facet(a, c, d);
}

// 12 triangles, counter-clockwise when seen from outside.
void writeBox(std::ostringstream& out, const Box& b) {
    const double p[8][3] = {{b.x0, b.y0, b.z0}, {b.x1, b.y0, b.z0}, {b.x1, b.y1, b.z0}, {b.x0, b.y1, b.z0},
                            {b.x0, b.y0, b.z1}, {b.x1, b.y0, b.z1}, {b.x1, b.y1, b.z1}, {b.x0, b.y1, b.z1}};
    const double nz[3] = {0, 0, -1}, pz[3] = {0, 0, 1}, ny[3] = {0, -1, 0}, py[3] = {0, 1, 0}, nx[3] = {-1, 0, 0},
                 px[3] = {1, 0, 0};
    writeQuad(out, nz, p[0], p[3], p[2], p[1]);
    writeQuad(out, pz, p[4], p[5], p[6], p[7]);
    writeQuad(out, ny, p[0], p[1], p[5], p[4]);
    writeQuad(out, py, p[3], p[7], p[6], p[2]);
    writeQuad(out, nx, p[0], p[4], p[7], p[3]);
    writeQuad(out, px, p[1], p[2], p[6], p[5]);
}

std::string makeStl() {
    std::ostringstream out;
    out << "solid heatsink_fins_mm\n";
    writeBox(out, {0, 0, 0, kBaseX, kBaseY, kBaseZ});
    for (int i = 0; i < kFins; ++i) {
        writeBox(out, {finX0(i), 0, kBaseZ, finX0(i) + kFinThickness, kBaseY, kBaseZ + kFinHeight});
    }
    out << "endsolid heatsink_fins_mm\n";
    return out.str();
}

// Synthetic field: a Gaussian hot spot under the base centre (a chip), and an
// exponential-ish fall-off up each fin using the classic straight-fin profile
// cosh(m(H - s)) / cosh(mH). Plausible looking, not a solved result.
double temperatureAt(double x_mm, double y_mm, double z_mm) {
    const double ambient = 25.0, peakRise = 55.0, spread = 18.0;
    const double dx = x_mm - kBaseX / 2, dy = y_mm - kBaseY / 2;
    const double base = ambient + peakRise * std::exp(-(dx * dx + dy * dy) / (2 * spread * spread)) -
                        1.5 * (z_mm < kBaseZ ? z_mm : kBaseZ) / kBaseZ;
    if (z_mm <= kBaseZ) return base;
    const double m = 0.06;  // 1/mm
    const double s = z_mm - kBaseZ;
    return ambient + (base - ambient) * std::cosh(m * (kFinHeight - s)) / std::cosh(m * kFinHeight);
}

std::string makeCsv() {
    wb::io::CsvWriter csv({"node_id", "x_m", "y_m", "z_m", "temperature_C"});
    csv.comment("SYNTHETIC DATA - self-created for the workbench demo, NOT an ANSYS export.");
    csv.comment("Same column schema as an ANSYS nodal temperature export: node_id,x_m,y_m,z_m,temperature_C");
    csv.comment("Part: heatsink_fins_mm.stl (geometry in mm; coordinates here in metres). Field: closed-form hot spot + fin fall-off.");
    csv.comment("Generated by src/tools/make_sample_data.cpp. Licence: CC0 / public domain.");

    long long id = 1;
    auto add = [&](double x, double y, double z) {
        csv.row(id++, x / 1000.0, y / 1000.0, z / 1000.0, std::round(temperatureAt(x, y, z) * 1000.0) / 1000.0);
    };
    // Base plate: 2.5 mm grid through the thickness.
    for (double z = 0.0; z <= kBaseZ + 1e-9; z += 2.5)
        for (double y = 0.0; y <= kBaseY + 1e-9; y += 2.5)
            for (double x = 0.0; x <= kBaseX + 1e-9; x += 2.5) add(x, y, z);
    // Fins: mid-plane of each fin, starting just above the base.
    for (int i = 0; i < kFins; ++i)
        for (double z = kBaseZ + 2.5; z <= kBaseZ + kFinHeight + 1e-9; z += 2.5)
            for (double y = 0.0; y <= kBaseY + 1e-9; y += 2.5) add(finX0(i) + kFinThickness / 2, y, z);
    return csv.str();
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::cerr << "usage: wb_make_sample_data <output-dir>\n";
        return 2;
    }
    const std::string dir = argv[1];
    try {
        wb::io::writeTextFileAtomic(dir + "/heatsink_fins_mm.stl", makeStl());
        wb::io::writeTextFileAtomic(dir + "/heatsink_nodal_SYNTHETIC.csv", makeCsv());
    } catch (const std::exception& e) {
        std::cerr << e.what() << '\n';
        return 1;
    }
    std::cout << "Wrote example files to " << dir << '\n';
    return 0;
}
